create trigger comment_notification after insert on public.comment
  for each row execute procedure public.notify_on_comment();

create or replace function public.search_posts(search_text text, result_limit integer default 20, result_offset integer default 0)
returns setof public.post language sql stable security invoker set search_path = public
as $$
  select p.* from public.post p
  left join public.categories c on c.id = p.categories_id
  where char_length(btrim(search_text)) between 1 and 100
    and (p.title ilike '%' || btrim(search_text) || '%' or c.topic ilike '%' || btrim(search_text) || '%')
  order by p.created_at desc, p.id desc
  limit least(greatest(result_limit, 1), 50) offset greatest(result_offset, 0);
$$;

create or replace function public.feed_posts(
  filter_topic text default null,
  filter_user uuid default null,
  sort_by text default 'newest',
  result_limit integer default 20,
  result_offset integer default 0
)
returns setof public.post language sql stable security invoker set search_path = public
as $$
  select p.* from public.post p
  left join public.categories c on c.id = p.categories_id
  where (filter_topic is null or lower(c.topic) = lower(filter_topic))
    and (filter_user is null or p.user_id = filter_user)
    and (
      sort_by not in ('top_day', 'top_week')
      or (sort_by = 'top_day' and p.created_at >= now() - interval '1 day')
      or (sort_by = 'top_week' and p.created_at >= now() - interval '7 days')
    )
  order by
    case when sort_by in ('top_day', 'top_week', 'top_all') then
      coalesce((select sum(case when v.upvote then 1 else -1 end) from public.vote v where v.post_id = p.id), 0)
    end desc,
    p.created_at desc,
    p.id desc
  limit least(greatest(result_limit, 1), 50) offset greatest(result_offset, 0);
$$;

create or replace function public.top_categories(result_limit integer default 5)
returns table (id bigint, topic text, post_count bigint)
language sql stable security invoker set search_path = public
as $$
  select c.id, c.topic, count(p.id)::bigint from public.categories c
  join public.post p on p.categories_id = c.id
  group by c.id, c.topic order by count(p.id) desc, c.topic asc
  limit least(greatest(result_limit, 1), 20);
$$;

