create or replace function public.notify_on_comment()
returns trigger language plpgsql security definer set search_path = public
as $$
declare post_owner uuid;
begin
  select user_id into post_owner from public.post where id = new.post_id;
  if post_owner is not null and new.user_id is not null and post_owner <> new.user_id then
    insert into public.notifications (recipient_id, actor_id, post_id, kind)
    values (post_owner, new.user_id, new.post_id, 'comment');
  end if;
  return new;
end;
$$;

